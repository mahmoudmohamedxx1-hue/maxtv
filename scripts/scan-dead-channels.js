/**
 * Full DaddyLive 24/7 channel health scan.
 * Probes every channel id from the catalog against the premium CDN edge
 * (same probe the app uses) and writes the dead-id seed to
 * src/data/daddylive-dead.ts for instant cold-start filtering.
 * (TS module, not JSON — JSON imports don't survive the standalone bundle.)
 * Usage: node scripts/scan-dead-channels.js [catalogJsonPath]
 */
const fs = require('fs');

const EDGE = 'edge.cowedd4855ws.sbs';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const OUT = '/home/z/my-project/src/data/daddylive-dead.ts';
const CONCURRENCY = 12;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function probeOne(id) {
  for (let attempt = 0; attempt < 3; attempt++) {
    if (attempt > 0) await sleep(600 + Math.random() * 700);
    try {
      const res = await fetch(`https://${EDGE}/premium${id}/index.m3u8`, {
        headers: { 'User-Agent': UA, Referer: 'https://dlcovx3o.online/' },
        signal: AbortSignal.timeout(6000),
        redirect: 'follow',
      });
      if (res.ok) return true;
      if (res.status === 404 || res.status === 410) return false; // definitive
      // 403/429/5xx → retry with backoff
    } catch {
      /* network hiccup → retry */
    }
  }
  return false;
}

(async () => {
  const src = process.argv[2] || '/tmp/live-ch.json';
  const catalog = JSON.parse(fs.readFileSync(src, 'utf8'));
  const channels = (Array.isArray(catalog) ? catalog : catalog.channels || []).filter(
    (c) => String(c.id).startsWith('dl247:')
  );
  const ids = channels.map((c) => ({ ref: c.ref, name: c.name }));
  console.log(`Scanning ${ids.length} DaddyLive channels @ concurrency ${CONCURRENCY}…`);

  const dead = [];
  let done = 0;
  let alive = 0;
  const queue = [...ids];
  const workers = Array.from({ length: CONCURRENCY }, async () => {
    while (queue.length) {
      const ch = queue.shift();
      if (!ch) break;
      const ok = await probeOne(ch.ref);
      done++;
      if (!ok) dead.push({ ref: ch.ref, name: ch.name });
      else alive++;
      if (done % 60 === 0) {
        console.log(`  …${done}/${ids.length} probed — ${dead.length} dead so far`);
      }
    }
  });
  await Promise.all(workers);

  const deadRefs = dead.map((d) => d.ref).sort((a, b) => Number(a) - Number(b));
  const lines = [
    '/** DaddyLive premium-CDN dead channel ids — full 24/7-index scan snapshot.',
    ' *  Auto-generated by scripts/scan-dead-channels.js (DO NOT hand-edit);',
    ' *  re-run the scanner whenever upstream drift is reported.',
    ' *  Kept as a TS module (not JSON) so the standalone server bundle',
    ' *  always includes it. */',
    'export const DEAD_DL_SCAN: readonly string[] = [',
  ];
  for (let i = 0; i < deadRefs.length; i += 12) {
    lines.push('  ' + deadRefs.slice(i, i + 12).map((x) => `'${x}'`).join(', ') + ',');
  }
  lines.push('];');
  lines.push(`export const DEAD_DL_SCANNED_AT = '${new Date().toISOString()}';`);
  fs.writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(`\nDone: ${alive} alive, ${dead.length} dead (${Math.round((dead.length / ids.length) * 100)}%)`);
  console.log(`Seed written to ${OUT}`);
  console.log('Dead sample:', dead.slice(0, 15).map((d) => `${d.name}(${d.ref})`).join(', '));
})().catch((e) => {
  console.error('FATAL:', e);
  process.exit(1);
});
